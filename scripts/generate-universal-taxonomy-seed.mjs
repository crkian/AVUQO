import {writeFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import {UNIVERSAL_DEPARTMENTS,EXISTING_CATEGORY_PARENTS,validateUniversalTaxonomy} from "../lib/taxonomy/universal-categories.mjs";

const quote=(s)=>s===null?"NULL":"'"+s.replaceAll("'","''")+"'";
const rows=(items)=>items.map(x=>"  ("+[quote(x.slug),quote(x.name),quote(x.parentSlug)].join(", ")+")").join(",\n");
const split=(list,n)=>Array.from({length:Math.ceil(list.length/n)},(_,i)=>list.slice(i*n,(i+1)*n));
const newGroups=UNIVERSAL_DEPARTMENTS.filter(x=>!x.existing);
const groupSlugSet=new Set(newGroups.map(x=>x.slug));
const roots=newGroups.filter(g=>!g.parentSlug||EXISTING_CATEGORY_PARENTS.includes(g.parentSlug));
const nested=newGroups.filter(g=>g.parentSlug&&groupSlugSet.has(g.parentSlug));
const leaves=UNIVERSAL_DEPARTMENTS.flatMap(g=>g.children);
const candidates=[...newGroups,...leaves];

function insertCategories(slugs){
 const names=slugs.map(quote).join(",");
 return `insert into public.categories (slug,name,parent_id,description,is_active)
select staged.slug,staged.name,parent.id,
 'AVUQO private universal taxonomy. Verify merchant rights and product identity before publishing.',false
from pg_temp.avuqo_universal_seed staged
left join public.categories parent on parent.slug=staged.parent_slug
where staged.slug in (${names})
on conflict(slug) do nothing;`;
}

export function generateUniversalSeed(){
 const validation=validateUniversalTaxonomy();
 if(!validation.ok||validation.newDepartments!==newGroups.length||validation.children!==leaves.length)throw Error(validation.errors.join("; "));
 const allSlugs=new Set(candidates.map(x=>x.slug));
 if(allSlugs.size!==candidates.length)throw Error("Duplicate candidate slugs");
 if(roots.length+nested.length!==newGroups.length)throw Error("Unsupported department nesting depth");
 const parentList=EXISTING_CATEGORY_PARENTS.map(quote).join(",");
 const statements=split(candidates,180).map(chunk=>`insert into pg_temp.avuqo_universal_seed(slug,name,parent_slug) values
${rows(chunk)};`).join("\n\n");
 const inserts=[insertCategories(roots.map(x=>x.slug)),
   ...(nested.length?[insertCategories(nested.map(x=>x.slug))]:[]),
   ...split(leaves,200).map(items=>insertCategories(items.map(x=>x.slug)))].join("\n\n");
 return `-- AVUQO universal category expansion. DATA SEED ONLY, NOT A PUBLIC LAUNCH.
-- Generated by scripts/generate-universal-taxonomy-seed.mjs. Do not hand-edit.
-- All ${candidates.length} new nodes are INACTIVE. Existing 33 nodes are preserved.
-- Neither imported feeds nor prices, product assignment, merchant approval or affiliate status change.
-- Sources: AVUQO project vision and independent coverage design; not merchant category permissions.
begin;
create temporary table avuqo_universal_seed(
 slug text primary key,
 name text not null,
 parent_slug text
) on commit drop;
${statements}

do $preflight$
begin
 if exists(select 1 from (select unnest(array[${parentList}]) slug) required
    left join public.categories c on c.slug=required.slug where c.id is null) then
  raise exception 'AVUQO canonical parent missing; abort universal taxonomy seed';
 end if;
 if (select count(*) from pg_temp.avuqo_universal_seed)<>${candidates.length} then
  raise exception 'Unexpected candidate count';
 end if;
 if exists(select 1 from pg_temp.avuqo_universal_seed t
    join public.categories c on c.slug=t.slug where c.is_active) then
  raise exception 'Refusing to alter pre-existing active category';
 end if;
end
$preflight$;

-- Insert departments first so all leaf parent identifiers resolve reliably.
${inserts}

do $verify$
begin
 if exists(select 1 from pg_temp.avuqo_universal_seed t
    left join public.categories c on c.slug=t.slug
    left join public.categories p on p.slug=t.parent_slug
    where c.id is null or c.is_active
      or c.parent_id is distinct from p.id) then
  raise exception 'Universal taxonomy insert incomplete, active, or mis-parented';
 end if;
 if (select count(*) from pg_temp.avuqo_universal_seed)<>${candidates.length} then
  raise exception 'Candidate count changed unexpectedly';
 end if;
end
$verify$;
commit;
`;
}
const dest=new URL("../supabase/seeds/20261030_universal_inactive_categories.sql",import.meta.url);
if(process.argv[1]&&fileURLToPath(import.meta.url)===process.argv[1])writeFileSync(dest,generateUniversalSeed(),"utf8");
