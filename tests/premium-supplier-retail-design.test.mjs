const read=path=>readFileSync(path,"utf8");

test("premium retailer studios preserve all 21 independent editorial identities and original categories",()=>{
 assert.equal(PARTNERS.length,21);
 assert.equal(Object.keys(PARTNER_STUDIOS).length,21);
 assert.equal(new Set(PARTNERS.map(p=>p.slug)).size,21);
 const styles=read("app/partners/studios.module.css");
 for(const studio of Object.values(PARTNER_STUDIOS))
  assert.ok(styles.includes('.hero[data-scene="'+studio.scene+'"]'),"missing original unique scene "+studio.scene);
 assert.match(styles,/--accent/);
 assert.match(styles,/Georgia/);
 assert.match(styles,/#fbf7f1/);
 assert.match(styles,/prefers-reduced-motion/);
});

